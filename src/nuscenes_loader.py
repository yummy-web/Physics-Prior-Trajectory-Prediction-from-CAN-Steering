"""
nuscenes_loader.py
nuScenes CAN bus expansion loader -> unified schema (matches loader/comma).

Per scene (~20s):
  <scene>_vehicle_monitor.json  (2Hz): steering(deg), vehicle_speed(km/h),
                                       yaw_rate(deg/s), throttle, brake, rear rpms
  <scene>_pose.json            (~50Hz): pos[x,y,z](m), orientation(quat), vel
Unified columns: t, x, y, yaw_unwrap(deg), obs_v(m/s), yaw_rate(deg/s),
                 curvature(1/m), steer(deg), can_speed(m/s)
"""
import os
import glob
import json
import pickle
import numpy as np
import pandas as pd

_BASE = os.path.join(os.path.dirname(__file__), "..", "..")
CACHE_FILE = os.path.join(os.path.dirname(__file__), ".nusc_cache.pkl")


def _cache_candidates():
    here = os.path.dirname(__file__)
    candidates = [CACHE_FILE]
    env_cache = os.environ.get("NUSC_CACHE_FILE")
    if env_cache:
        candidates.insert(0, env_cache)
    candidates.append(os.path.join(here, "..", "..", "..", "数据分析", "paper_experiments", ".nusc_cache.pkl"))
    return [os.path.abspath(c) for c in candidates]


def _cache_is_causal(cache):
    """Only reuse caches explicitly generated by the strict-PVH loader."""
    return os.path.exists(cache + ".strict_pvh_v1")


def _dataset_dir():
    roots = [_BASE, os.path.join(os.path.dirname(__file__), "..", "..", "..")]
    for root in roots:
        for d in glob.glob(os.path.join(root, "*")):
            # find folder that (recursively) contains *_vehicle_monitor.json
            hits = glob.glob(os.path.join(d, "**", "*_vehicle_monitor.json"), recursive=True)
            if hits:
                return os.path.dirname(hits[0])
    return None


def quat_yaw(q):
    w, x, y, z = q
    return np.degrees(np.arctan2(2 * (w * z + x * y), 1 - 2 * (y * y + z * z)))


def list_scenes(dd):
    files = sorted(glob.glob(os.path.join(dd, "scene-*_vehicle_monitor.json")))
    return [os.path.basename(f).replace("_vehicle_monitor.json", "") for f in files]


def _past_value_hold(t_src, v_src, t_q):
    """Causal sample-and-hold alignment using only timestamps <= query."""
    t_src = np.asarray(t_src, dtype=float).ravel()
    v_src = np.asarray(v_src).ravel()
    t_q = np.asarray(t_q, dtype=float).ravel()
    if len(t_src) == 0 or len(t_src) != len(v_src):
        raise ValueError("source timestamps and values must be non-empty and equally sized")
    order = np.argsort(t_src, kind="stable")
    t_src, v_src = t_src[order], v_src[order]
    idx = np.searchsorted(t_src, t_q, side="right") - 1
    valid = idx >= 0
    held = np.empty(t_q.shape, dtype=v_src.dtype)
    held[valid] = v_src[idx[valid]]
    return held, valid


def load_scene(dd, scene):
    pose = json.load(open(os.path.join(dd, scene + "_pose.json")))
    vm = json.load(open(os.path.join(dd, scene + "_vehicle_monitor.json")))
    pt = np.array([r["utime"] for r in pose], float) / 1e6
    x = np.array([r["pos"][0] for r in pose], float)
    y = np.array([r["pos"][1] for r in pose], float)
    yaw = np.unwrap(np.radians([quat_yaw(r["orientation"]) for r in pose]))
    # The pose/evaluation timeline is approximately 50 Hz.
    t0 = pt[0]
    t = pt - t0
    # CAN
    vt = np.array([r["utime"] for r in vm], float) / 1e6
    steer = np.array([r["steering"] for r in vm], float)
    vspeed = np.array([r["vehicle_speed"] for r in vm], float) / 3.6  # km/h -> m/s
    a_steer, valid_steer = _past_value_hold(vt, steer, pt)
    a_vspeed, valid_speed = _past_value_hold(vt, vspeed, pt)
    valid = valid_steer & valid_speed
    if valid.sum() < 3:
        raise ValueError("fewer than three pose samples have causal CAN support")
    pt, x, y, yaw = pt[valid], x[valid], y[valid], yaw[valid]
    a_steer, a_vspeed = a_steer[valid], a_vspeed[valid]
    t = pt - pt[0]

    dt = np.gradient(t)
    vx = np.gradient(x) / dt; vy = np.gradient(y) / dt
    obs_v = np.hypot(vx, vy)
    yaw_unwrap = np.degrees(yaw)
    yaw_rate = np.degrees(np.gradient(yaw) / dt)
    curvature = np.radians(yaw_rate) / (obs_v + 1e-3)
    return pd.DataFrame({
        "seg": scene, "t": t, "x": x, "y": y, "yaw_unwrap": yaw_unwrap,
        "obs_v": obs_v, "yaw_rate": yaw_rate, "curvature": curvature,
        "steer": a_steer, "can_speed": a_vspeed,
    })


def load_all_cached(min_speed=3.0, min_steer_std=5.0, use_cache=True, verbose=True, max_scenes=None):
    if use_cache:
        for cache in _cache_candidates():
            if os.path.exists(cache) and _cache_is_causal(cache):
                if verbose:
                    print("  [cache] loading from %s" % cache)
                with open(cache, "rb") as f:
                    cached = pickle.load(f)
                if len(cached) > 0:
                    return cached
                if verbose:
                    print("  [cache] skipped empty cache")
    dd = _dataset_dir()
    if dd is None:
        raise FileNotFoundError("nuScenes CAN expansion not found under 公开数据集/")
    scenes = list_scenes(dd)
    if max_scenes:
        scenes = scenes[:max_scenes]
    out = {}
    for sc in scenes:
        try:
            df = load_scene(dd, sc)
        except Exception:
            continue
        if df["obs_v"].mean() < min_speed:
            continue
        if df["steer"].std() < min_steer_std:
            continue
        if len(df) < 100:
            continue
        out[sc] = df
    if verbose:
        print("  [load] nuScenes: %d/%d usable scenes (v>%.0f, steer_std>%.0f)"
              % (len(out), len(scenes), min_speed, min_steer_std))
    if use_cache:
        with open(CACHE_FILE, "wb") as f:
            pickle.dump(out, f)
        with open(CACHE_FILE + ".strict_pvh_v1", "w", encoding="utf-8") as f:
            f.write("strict_past_value_hold_v1\n")
    return out


if __name__ == "__main__":
    import time
    dd = _dataset_dir()
    scenes = list_scenes(dd)
    print("found %d scenes in %s" % (len(scenes), dd))
    t0 = time.time()
    out = {}
    for sc in scenes:
        try:
            df = load_scene(dd, sc)
        except Exception:
            continue
        if df["obs_v"].mean() < 3.0 or df["steer"].std() < 5.0 or len(df) < 100:
            continue
        out[sc] = df
    with open(CACHE_FILE, "wb") as f:
        pickle.dump(out, f)
    tot = sum(df["t"].iloc[-1] for df in out.values())
    print("usable %d/%d scenes, %.0fs (%.1f min); cache written." % (len(out), len(scenes), tot, tot / 60))
